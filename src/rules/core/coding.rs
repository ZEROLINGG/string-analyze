lazy_rule!(
    RE_FOYAN = r#"(?:佛曰|如是我闻|舍利弗|须菩提|婆伽婆|摩诃萨|世尊|比丘|阿耨多罗|三藐三菩提)?[：:]?\s*[\u{4e00}-\u{9fa5}]{15,}"#,
    "发现 佛曰编码",
    40,
    |slice, _| {
        let trimmed = slice.trim_start();
        if trimmed.starts_with("佛曰") || trimmed.starts_with("如来") || trimmed.starts_with("如是我闻") {
            return true;
        }

        // 核心特征字
        let high_weight_dict = [
            '皤', '埵', '阇', '墀', '迦', '楞', '咩', '钵', '醯', '羯',
            '唎', '娑', '谛', '穆', '怛', '陀', '哆',
        ];

        // 次核心特征字
        let low_weight_dict = [
            '佛', '菩', '提', '萨', '摩', '诃', '般', '若', '波', '罗',
            '蜜', '阿', '弥', '舍', '利', '南', '无'
        ];

        let mut score = 0;

        let check_len = slice.chars().count().min(50);

        for c in slice.chars().take(check_len) {
            if high_weight_dict.contains(&c) {
                score += 2;
            } else if low_weight_dict.contains(&c) {
                score += 1;
            }
        }

        score >= 10
    }
);
